"""Render tests/tolerances.toml from the measured noise report (DESIGN.md §9.2). Called by noise_stats.py.

The file uses a deliberately small TOML subset ([a.b] tables, `key = number | "string" | bool`, # comments), which
src/tolerances.rs parses without a TOML dependency. Every threshold is FACTOR x a measured envelope, and the
measured numbers sit next to it under `measured_*` keys, so a reviewer sees what each number derives from.
"""
from __future__ import annotations

import datetime

TOP1_MARGIN_FLOOR = 0.02  # DESIGN §9.2 starting value for the top-1 agreement margin
FACTOR = 1.5  # §9.2: "no worse than bf16-reference vs fp32 truth x 1.5", applied to every envelope below


def _num(x: float) -> str:
    return f"{x:.4g}" if x != 0 else "0.0"


def _env(report: dict, groups: list[str], stat: str, q: str) -> tuple[float, str]:
    """Largest measured value of `stat`/`q` over the pooled groups, with the group it came from."""
    best, src = 0.0, ""
    for g in groups:
        v = (report["groups"].get(g) or {}).get(stat, {}).get(q)
        if v is not None and v >= best:
            best, src = v, g
    if not src:
        raise SystemExit(f"no measurement for {stat}.{q} in {groups}: run the golden runs first")
    return best, src


def render(report: dict) -> str:
    g = report["groups"]
    L = [
        "# sysone tolerances (DESIGN.md §9.2). Every test reads its thresholds here; loosening one is a reviewed",
        "# one-line change. Generated by reference/noise_stats.py --write-tolerances from the W1b dev goldens;",
        "# hand edits are fine but must keep the measured_* numbers they derive from.",
        "#",
        "# Rule (relative, binding): a threshold is FACTOR x the envelope the *reference itself* shows, where the",
        "# envelope is the largest measured spread among the named reference-vs-reference comparisons:",
        "#   bf16_vs_fp32      qev bf16 vs qev fp32 (same fork path), pooled over batched and sequential",
        "#   bf16_fork         qev bf16 batched fork vs sequential branches (batch-dependent kernel rounding)",
        "#   nvfp4_cross_process  NVFP4 QDQ per-question reference, 3 fresh processes, pairwise",
        "#   nvfp4_perq_vs_shared_prefix  NVFP4 QDQ per-question vs the shared-prefix served path (batched+seq)",
        "# Probabilities are per option of each branch (softmax of the slot logits at T = 1); dp = |p_a - p_b|.",
        "# Quantiles are nearest-rank over all options of all compared branches. Tests must still print their",
        "# own p50/p99/max, not just pass/fail.",
        "",
        "schema = 1",
        f'generated = "{datetime.date.today().isoformat()}"',
        'source = "tests/golden/dev/model/noise_report.json"',
        'tier = "dev (GB10 aarch64, torch 2.13.0+cu132, transformers 5.19.0, torch-fallback GDN, sdpa)"',
        f"factor = {FACTOR}",
        "",
    ]

    def gate(table: str, doc: list[str], groups: list[str], stats: list[tuple[str, str, str]], extra=()):
        L.extend(["", *(f"# {d}" for d in doc), f"[{table}]", f'envelope = "{"+".join(groups)}"'])
        for key, stat, q in stats:
            v, src = _env(report, groups, stat, q)
            L.append(f"{key} = {_num(FACTOR * v)}")
            L.append(f"measured_{key} = {_num(v)}  # {src}: {stat} {q}")
        L.extend(extra)

    e2e = [("dp_p99", "dp_option", "p99"), ("dp_max", "dp_option", "max"),
           ("dlogit_p99", "dlogit", "p99"), ("dlogit_max", "dlogit", "max")]
    bf16_env = ["bf16_vs_fp32", "bf16_fork"]
    flip_margin = max((g.get(x) or {}).get("top1_flip_max_ref_margin", 0) for x in bf16_env)
    top1 = max(FACTOR * flip_margin, TOP1_MARGIN_FLOOR)
    gate("e2e.bf16", ["sysone bf16 vs the bf16 reference (qev batched): slot logits and per-option probabilities.",
                      "top1_margin: the top choice must agree wherever the reference's top-1 margin exceeds it.",
                      "It is max(FACTOR x measured_top1_margin, floor_top1_margin): the largest reference margin at",
                      "which any reference pair in the envelope flipped its top choice, x FACTOR, but never below",
                      "the DESIGN §9.2 starting value (floor), because a handful of flips over the dev corpus is too",
                      "few to bound the flip margin tightly."],
         bf16_env, e2e, [f"top1_margin = {_num(top1)}",
                         f"measured_top1_margin = {_num(flip_margin)}  # {'+'.join(bf16_env)}: top1_flip_max_ref_margin",
                         f"floor_top1_margin = {_num(TOP1_MARGIN_FLOOR)}  # DESIGN §9.2 starting value",
                         "# flips summed over the envelope's pairs (the same branch can flip in several pairs)",
                         f"measured_top1_flips = {sum((g.get(x) or {}).get('top1_flips', 0) for x in bf16_env)}",
                         f"design_start_dp_p99 = 0.01",
                         f"design_start_dp_max = 0.05"])
    gate("e2e.fp32_truth", ["sysone (bf16) vs the fp32 reference: within FACTOR x the bf16 reference's own error vs",
                            "fp32."], ["bf16_vs_fp32"], e2e)
    gate("batch_invariance", ["The same request alone vs packed with 63 others (sysone vs itself). Envelope: the",
                              "reference's own batch dependence (batched fork vs sequential)."],
         ["bf16_fork"], [("dp_max", "dp_option", "max"), ("dlogit_max", "dlogit", "max")],
         ["design_start_dp_max = 0.01"])
    cp = g.get("nvfp4_cross_process") or {}
    gate("nvfp4", ["sysone NVFP4 vs the NVFP4 QDQ per-question reference (not bf16): within its own run-to-run",
                   "drift and its per-question vs shared-prefix spread (DESIGN §3.1, §9.2).",
                   "Measured: cross-process drift on this box is "
                   f"{_num(cp.get('dp_option', {}).get('max', float('nan')))} (deterministic torch-fallback GDN), but the",
                   "per-question and shared-prefix paths differ ~10x more than in bf16: FP4 activation rounding",
                   "amplifies bf16 kernel-shape noise (see noise_report.json hidden.*_served_vs_per_question). The",
                   "§3.1 equivalence holds in exact arithmetic only, so this gate is wide; tighten it by comparing",
                   "sysone against the shared-prefix QDQ path once W4 can run the same packing."],
         ["nvfp4_cross_process", "nvfp4_perq_vs_shared_prefix"], e2e)
    nv = g.get("nvfp4_vs_bf16") or {}
    if nv:
        L.extend(["", "# Quality information only (no gate): NVFP4 QDQ vs bf16, same paths.", "[nvfp4.vs_bf16]",
                  f"measured_dp_p50 = {_num(nv['dp_option']['p50'])}",
                  f"measured_dp_p99 = {_num(nv['dp_option']['p99'])}",
                  f"measured_dp_max = {_num(nv['dp_option']['max'])}",
                  f"measured_top1_flips = {nv['top1_flips']}"])
    # Per-layer hidden states ([model.hidden.*], gate (a)) are no longer derived from the 100 sampled rows of the
    # W1b dumps: reference/hidden_dense.py writes them as a marked block over the dense row set (Phase 2a A1).
    L.extend(["", "# [kernels.*]: per-op tolerances belong to W3's kernel tests (fp32 torch reference per op, §9.2);",
              "# add them here as [kernels.<op>] tables with the measurement each derives from.", ""])
    return "\n".join(L)


def keep_generated_blocks(old: str, new: str) -> str:
    """Re-append the marked blocks other generators own (`# >>> ... >>>` to `# <<< ... <<<`, e.g. [eval] from
    reference/eval/stats.py and [model.hidden] from reference/hidden_dense.py) that `new` lacks."""
    out, rest = new.rstrip("\n") + "\n", old
    while "# >>> " in rest:
        start = rest.index("# >>> ")
        end_tag = rest.index("# <<< ", start)
        end = rest.index("\n", end_tag) + 1
        block = rest[start:end]
        if block.splitlines()[0] not in out:
            out += "\n" + block
        rest = rest[end:]
    return out
