#!/usr/bin/env bash
# x86 test runner (docs/x86/TASKS.md T0/T2): the tests that need no external golden dumps, per GPU, each GPU under
# its own lock. Results (sanitised test output, summary.tsv, metadata.json) go to
# benchmarks/results/x86/<card-slug>/<date>/gpu<N>-tests/ and benchmarks/results/x86/host/<date>/cpu-tests/.
#
#   scripts/x86/run_tests.sh --model DIR [--gpus 0,2|all] [--nvfp4 DIR] [--external] [--slow]
#   scripts/x86/run_tests.sh --no-model [--gpus ...]      only the tests that need no checkpoint
#
#   --model DIR   the elephant-1 (bf16) checkpoint directory (default: $SYSONE_MODEL_DIR)
#   --nvfp4 DIR   the private NVFP4 checkpoint, only if the user provided it on this machine
#   --gpus LIST   GPU indices (nvidia-smi numbering), default all
#   --external    also run the tests that need data from the GB10 reference harness (EXTERNAL below). They are
#                 expected to FAIL on this machine (missing ../sysone-ref dumps / generated NVFP4 data): they fail
#                 loudly, they never skip. Without --external they are listed as NOT RUN.
#   --slow        also run the ignored CPU reference check (tests/cpu_ref.rs, minutes of CPU, needs the checkpoint)
#
# Test groups (docs/ARCHITECTURE.md §6.3 has each test's data prerequisites):
#   CPU           lib unit tests, render_golden_shape, scripts                  no GPU, no checkpoint
#   CPU_MODEL     frontend_golden, frontend_assemble, server_e2e                no GPU; tokenizer + chat template
#   GPU           kernels_norm, kernels_attn, kernels_gdn (tile + simt), kernels_simt, kernels_nvfp4 (all but the
#                 layer-0 case), kernels_nvfp4_fused, engine_gemm, engine_graph, platform_gpu   per GPU; no checkpoint
#   GPU_MODEL     engine_loader (bf16; NVFP4 cases only with --nvfp4), engine_e2e, engine_server   per GPU; checkpoint
#                 (engine_e2e_nvfp4: SYSONE_ENGINE=nvfp4 engine_e2e, only with --nvfp4)
#   EXTERNAL      engine_layers (hidden-state dumps under ../sysone-ref), kernels_nvfp4::gemm_layer0_vs_compressed_tensors_qdq
#                 (reference/nvfp4/data, generated by the reference venv from the NVFP4 checkpoint)
set -uo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cd "$X86_ROOT"

model="${SYSONE_MODEL_DIR:-}" nvfp4="" gpus=all external=0 slow=0 nomodel=0
while [ $# -gt 0 ]; do
    case "$1" in
        --model) model="$2"; shift ;;
        --nvfp4) nvfp4="$2"; shift ;;
        --gpus) gpus="$2"; shift ;;
        --external) external=1 ;;
        --slow) slow=1 ;;
        --no-model) nomodel=1 ;;
        -h|--help) sed -n '2,30p' "$0"; exit 0 ;;
        *) x86_die "unknown argument $1 (see --help)" ;;
    esac
    shift
done
if [ "$nomodel" = 0 ]; then
    [ -n "$model" ] || x86_die "no checkpoint: pass --model DIR (or set SYSONE_MODEL_DIR), or --no-model"
    [ -f "$model/tokenizer.json" ] && [ -f "$model/config.json" ] || x86_die "--model $model is not an elephant-1 checkpoint directory"
    model=$(cd "$model" && pwd)
    export SYSONE_MODEL_DIR="$model" SYSONE_BF16_DIR="$model"
else
    model=""
fi
# engine_loader skips (with a message) when a checkpoint is absent; point it at nothing unless one was given, so it
# never picks up a default path.
if [ -n "$nvfp4" ]; then export SYSONE_NVFP4_DIR="$(cd "$nvfp4" && pwd)"; else export SYSONE_NVFP4_DIR=/nonexistent/nvfp4-not-provided; fi
[ "$gpus" = all ] && gpus=$(x86_gpu_indices | paste -sd,)
IFS=, read -r -a gpu_list <<< "$gpus"

echo "x86: building the tests (outside the GPU lock)" >&2
cargo test --release --all-targets --no-run >/dev/null 2>&1 || { cargo test --release --all-targets --no-run 2>&1 | tail -20; x86_die "test build failed"; }

failed=0
# t DIR NAME GPU|- ARGS...: one cargo test invocation; GPU "-" runs without the GPU lock (CPU-only tests).
t() {
    local dir="$1" name="$2" gpu="$3"; shift 3
    if [ "$gpu" = - ]; then
        local t0=$(date +%s) rc
        echo "x86: [cpu] $name" >&2
        cargo test --release "$@" > "$dir/$name.txt" 2> "$X86_LOGS/host_$name.log"; rc=$?
        x86_sanitize "$dir/$name.txt"
        printf '%s\t%s\t%s\n' "$name" "$rc" "$(( $(date +%s) - t0 ))" >> "$dir/summary.tsv"
        [ "$rc" = 0 ] || { echo "x86: [cpu] $name FAILED (exit $rc)" >&2; failed=1; }
    else
        x86_job "$dir" "$name" "$gpu" cargo test --release "$@" || failed=1
    fi
}
not_run() { printf '%s\tNOT-RUN\t%s\n' "$2" "$3" >> "$1/summary.tsv"; echo "x86: NOT RUN $2 ($3)" >&2; }
mkdir -p "$X86_LOGS"

# Once per host: CPU tests.
d=$(x86_results_dir host cpu-tests)
x86_write_metadata "$d" "${gpu_list[0]}" cpu-tests "GPU-free tests; gpu fields describe GPU ${gpu_list[0]} only"
t "$d" lib - --lib
t "$d" render_golden_shape - --test render_golden_shape
t "$d" scripts - --test scripts
if [ -n "$model" ]; then
    t "$d" frontend_golden - --test frontend_golden
    t "$d" frontend_assemble - --test frontend_assemble
    t "$d" server_e2e - --test server_e2e
    if [ "$slow" = 1 ]; then t "$d" cpu_ref - --test cpu_ref -- --ignored --nocapture; else not_run "$d" cpu_ref "ignored, minutes of CPU: --slow"; fi
else
    for n in frontend_golden frontend_assemble server_e2e cpu_ref; do not_run "$d" "$n" "needs the checkpoint (--model)"; done
fi
x86_seal "$d" || failed=1
dirs=("$d")

# Per GPU, one GPU at a time (each job holds that GPU's lock).
for g in "${gpu_list[@]}"; do
    d=$(x86_results_dir "$g" "gpu$g-tests")
    x86_write_metadata "$d" "$g" tests "run_tests.sh, model $([ -n "$model" ] && echo yes || echo no), nvfp4 $([ -n "$nvfp4" ] && echo yes || echo no)"
    t "$d" platform_gpu "$g" --test platform_gpu
    t "$d" kernels_simt "$g" --test kernels_simt -- --nocapture
    t "$d" kernels_norm "$g" --test kernels_norm
    t "$d" kernels_attn "$g" --test kernels_attn
    t "$d" kernels_gdn "$g" --test kernels_gdn -- --test-threads=1
    t "$d" kernels_nvfp4 "$g" --test kernels_nvfp4 -- --skip gemm_layer0_vs_compressed_tensors_qdq
    t "$d" kernels_nvfp4_fused "$g" --test kernels_nvfp4_fused -- --nocapture --test-threads=1
    t "$d" engine_gemm "$g" --test engine_gemm
    t "$d" engine_graph "$g" --test engine_graph
    if [ -n "$model" ]; then
        t "$d" engine_loader "$g" --test engine_loader -- --nocapture --test-threads=1
        t "$d" engine_e2e "$g" --test engine_e2e -- --nocapture --test-threads=1
        t "$d" engine_server "$g" --test engine_server -- --nocapture --test-threads=1
    else
        for n in engine_loader engine_e2e engine_server; do not_run "$d" "$n" "needs the checkpoint (--model)"; done
    fi
    if [ -n "$nvfp4" ]; then
        # The nvfp4 engine (N1) on the NVFP4 checkpoint: gates vs the NVFP4 goldens, batch invariance, graph
        # replay, fused vs standalone quantize.
        export SYSONE_ENGINE=nvfp4
        t "$d" engine_e2e_nvfp4 "$g" --test engine_e2e -- --nocapture --test-threads=1
        unset SYSONE_ENGINE
    else
        not_run "$d" engine_e2e_nvfp4 "needs the private NVFP4 checkpoint (--nvfp4), only if the user provided it"
    fi
    if [ "$external" = 1 ]; then
        t "$d" engine_layers "$g" --test engine_layers -- --nocapture --test-threads=1
        t "$d" kernels_nvfp4_layer0 "$g" --test kernels_nvfp4 -- --exact gemm_layer0_vs_compressed_tensors_qdq
    else
        not_run "$d" engine_layers "needs ../sysone-ref hidden-state dumps (GB10 reference harness): --external"
        not_run "$d" kernels_nvfp4_layer0 "needs reference/nvfp4/data (reference venv + NVFP4 checkpoint): --external"
    fi
    x86_seal "$d" || failed=1
    dirs+=("$d")
done

echo
echo "x86 test summary (exit code per test target; NOT-RUN = not attempted, see reason):"
for d in "${dirs[@]}"; do
    [ -d "$d" ] || continue
    echo "  ${d#"$X86_ROOT"/}"
    awk -F'\t' '{ printf "    %-22s %s\n", $1, ($2 == "0" ? "ok" : ($2 == "NOT-RUN" ? "NOT RUN: " $3 : "FAILED (exit " $2 ")")) }' "$d/summary.tsv"
done
exit "$failed"
